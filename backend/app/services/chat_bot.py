class BeautyChatBot:
    """چت‌بات هوشمند فارسی با حافظه عمیق"""

    def __init__(self):
        self._history: Dict[str, List[dict]] = {}
        self._last_replies: Dict[str, str] = {}
        self._user_state: Dict[str, dict] = {}  # name, age, areas_interested, stage

    def _get_state(self, uid: str) -> dict:
        if uid not in self._user_state:
            self._user_state[uid] = {
                'name': None,
                'age': None,
                'areas': [],         # ناحیه‌هایی که کاربر پرسیده
                'stage': 'welcome',  # welcome | analyzing | showing_result | consultation
                'last_intent': None,
                'msg_count': 0,
            }
        return self._user_state[uid]

    # ---------- API اصلی ----------
    def reply(self, user_id: str, text: str,
              has_photo: bool = False,
              last_result_ok: Optional[bool] = None,
              use_llm: bool = True) -> dict:
        intent = detect_intent(text)
        state = self._get_state(user_id)
        state['last_intent'] = intent
        state['msg_count'] += 1

        # ذخیره پیام کاربر
        self._remember(user_id, {'role': 'user', 'text': text})

        # استخراج اطلاعات
        new_name = extract_name(text)
        if new_name:
            state['name'] = new_name.capitalize()

        age = extract_age(text)
        if age:
            state['age'] = age

        area = detect_area(text)
        if area and area not in state['areas']:
            state['areas'].append(area)

        # ---------- ۱) تلاش با LLM (اگر تنظیم شده) ----------
        if use_llm and intent not in ('edit',):
            llm_msg = self._llm_reply(user_id, text, state)
            if llm_msg:
                self._remember(user_id, {'role': 'ai', 'text': llm_msg})
                return {'reply': llm_msg, 'intent': intent,
                        'is_edit_request': False, 'engine': 'llm'}

        # ---------- ۲) موتور محلی ----------
        msg: Optional[str] = None
        name = state.get('name')

        if intent == 'edit':
            msg = None  # موتور پردازش تصویر جواب میدهد
            state['stage'] = 'analyzing'
        elif intent == 'greeting':
            if name:
                msg = random.choice(GREETING_WITH_NAME).format(name=name)
            else:
                if state['msg_count'] <= 2 or state['stage'] == 'welcome':
                    msg = self._pick(user_id, GREETINGS)
                else:
                    msg = self._pick(user_id, RETURNING_GREETINGS)
            state['stage'] = 'welcome'
        elif intent == 'thanks':
            msg = self._pick(user_id, THANKS)
        elif intent == 'praise':
            msg = self._pick(user_id, PRAISE_ACK)
        elif intent == 'worry':
            msg = self._pick(user_id, WORRY_REPLIES)
        elif intent == 'joke':
            msg = self._pick(user_id, JOKES)
        elif intent == 'help':
            msg = random.choice(HELP_REPLIES)
        elif intent == 'price':
            if area and area in AREA_INFO:
                msg = (f"سؤال خوبی پرسیدی! 💰\n\n"
                       f"{AREA_INFO[area]}\n\n"
                       f"البته قیمت نهایی به شهر، پزشک و کلینیک بستگی داره. "
                       f"وقتی عکست رو بفرستی، برآورد دقیق‌تری بر اساس چهره‌ت میدم.\n\n"
                       f"دوست داری بیشتر درباره {KNOWLEDGE[area]['name_fa']} بدونی؟ یا بریم سراغ یه ناحیه دیگه؟")
                state['stage'] = 'consultation'
            else:
                msg = ("سؤال منطقی‌ای! 💰 قیمت هر ناحیه متفاوته:\n\n"
                       "👃 بینی: ۱۸ تا ۶۵ میلیون\n"
                       "👄 لب: ۴.۵ تا ۱۸ میلیون\n"
                       "😊 گونه: ۶ تا ۲۲ میلیون\n"
                       "🦴 فک و چانه: ۱۲ تا ۴۵ میلیون\n"
                       "👁 چشم و ابرو: ۸ تا ۳۵ میلیون\n\n"
                       "بگو کدوم ناحیه رو میخوای تا جزئیات کامل بگم!")
        elif intent == 'doctor':
            msg = ("برای این کار بهترین‌ها رو دارم 👨‍⚕️\n\n"
                   "تیم ما شامل جراحان متخصص با سابقه بالای ۱۰ سال و نمونه‌کارهای متعدد هستن.\n"
                   "مشاوره اولیه رایگانه! فقط کافیه:\n"
                   "۱) عکس خودت رو بفرستی\n"
                   "۲) بگی کدوم تغییر رو میخوای\n"
                   "۳) من بهترین پزشک‌ها رو بر اساس نیازت معرفی میکنم\n\n"
                   "بزن بریم؟")
            state['stage'] = 'consultation'
        elif intent == 'sad':
            msg = self._pick(user_id, SAD_REPLIES)
        elif intent == 'how':
            msg = random.choice(HOW_IT_WORKS)
        elif intent == 'result_like':
            msg = self._pick(user_id, COMPLIMENT_RESULT)
            if name:
                msg = msg.replace('!', f' {name} جان!')
            state['stage'] = 'showing_result'
        elif intent == 'name_intro':
            if name:
                msg = random.choice(NAME_CAPTURE).format(name=name)
                # پیشنهاد بعدی
                if state['msg_count'] == 1:
                    msg += "\n\nیه عکس بفرست تا ببینم چه پیشنهادی برات دارم 📸"
            else:
                msg = "چه خوب! خودم رو بوتی معرفی میکنم ✨\nتو چطور صدام کنم؟ اسمت رو بگو تا صمیمی حرف بزنیم!"
        # اگر کاربر درباره ناحیه خاصی پرسیده (نه edit request)
        elif area and area in AREA_INFO and intent not in ('edit',):
            info = KNOWLEDGE[area]
            msg = (f"درباره {info['name_fa']} سوال داری، عالیه! 💫\n\n"
                   f"{AREA_INFO[area]}\n\n"
                   f"سوال دیگه‌ای داری یا دوست داری یه شبیه‌سازی روی عکست ببینیم؟")
            state['stage'] = 'consultation'
        elif not has_photo and last_result_ok is None and state['msg_count'] <= 3:
            msg = self._pick(user_id, ASK_PHOTO)
        else:
            msg = self._pick(user_id, FALLBACKS)

        # اضافه کردن پیشنهاد مشاوره اگر کاربر آماده‌ست
        if (msg and state['msg_count'] > 4 and state['stage'] != 'consultation'
                and intent not in ('consultation', 'worry') and random.random() < 0.3):
            msg += "\n\n" + random.choice(CONSULTATION_INVITES)

        if msg:
            self._remember(user_id, {'role': 'ai', 'text': msg})
        return {'reply': msg, 'intent': intent,
                'is_edit_request': intent == 'edit', 'engine': 'local'}

    # ---------- LLM ----------
    def _llm_reply(self, user_id: str, text: str, state: dict) -> Optional[str]:
        """پاسخ از مدل زبانی - برایز بیصدا در صورت خطا"""
        if not LLM_URL:
            return None

        msgs = [{'role': 'system', 'content': PERSONA_SYSTEM}]

        # اضافه کردن context کاربر
        context_parts = []
        if state.get('name'):
            context_parts.append(f"اسم کاربر: {state['name']}")
        if state.get('age'):
            context_parts.append(f"سن: {state['age']}")
        if state.get('areas'):
            context_parts.append(f"نواحی مورد علاقه: {', '.join(state['areas'])}")
        if state.get('stage'):
            context_parts.append(f"مرحله فعلی: {state['stage']}")
        if context_parts:
            msgs.append({'role': 'system',
                         'content': 'اطلاعات کاربر: ' + ' | '.join(context_parts)})

        msgs += self.history(user_id)[-10:]

        payload = json.dumps({
            'model': LLM_MODEL,
            'messages': msgs,
            'max_tokens': 200,
            'temperature': 0.85,
        }).encode()
        req = urllib.request.Request(
            f'{LLM_URL}/chat/completions', data=payload,
            headers={'Content-Type': 'application/json',
                     **({'Authorization': f'Bearer {LLM_KEY}'} if LLM_KEY else {})},
            method='POST')
        try:
            with urllib.request.urlopen(req, timeout=LLM_TIMEOUT) as r:
                data = json.loads(r.read().decode())
            out = (data['choices'][0]['message']['content'] or '').strip()
            return out or None
        except Exception as e:
            logger.info(f'LLM unavailable, falling back to local: {e}')
            return None

    # ---------- خطوط کمکی ----------
    def processing_line(self) -> str:
        return random.choice(PROCESSING_LINES)

    def success_line(self) -> str:
        return random.choice(SUCCESS_LINES)

    def no_face_line(self) -> str:
        return random.choice(NO_FACE_TIPS)

    def ask_photo_line(self, uid: str) -> str:
        return self._pick(uid, ASK_PHOTO)

    def welcome_back_line(self, uid: str) -> str:
        return self._pick(uid, RETURNING_GREETINGS)

    # ---------- ابزار داخلی ----------
    def _pick(self, uid: str, pool: List[str]) -> str:
        if not pool:
            return ''
        choice = random.choice(pool)
        for _ in range(8):
            if choice != self._last_replies.get(uid):
                break
            choice = random.choice(pool)
        self._last_replies[uid] = choice
        return choice

    def _remember(self, uid: str, item: dict) -> None:
        h = self._history.setdefault(uid, [])
        h.append(item)
        del h[:-30]  # ۱۵ تبادل آخر

    def history(self, uid: str) -> List[dict]:
        return list(self._history.get(uid, []))

    def get_state(self, uid: str) -> dict:
        """برای استفاده در API: وضعیت فعلی کاربر"""
        return dict(self._get_state(uid))


