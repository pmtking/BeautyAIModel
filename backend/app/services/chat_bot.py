# تشخیص معرفی اسم
_NAME_PAT = re.compile(
    r'(?:اسمم|اسسمم?|اسم\s*من|من\s+اسمم)\s+([آابپتثجچحخدذرزژسشصضطظعغفقکگلمنوهی]{2,15})'
    r'(?:\s+(?:هستم|هست|است|امت|ام))?\s*$')

# تشخیص عدد/سن
_AGE_PAT = re.compile(r'(\d{1,2})\s*(?:ساله|سال\s+سن|سال\s+دارم|years?\s+old)')


def detect_intent(text: str) -> str:
    """تشخیص نیت با وزن‌دهی - بهترین match را برمیگرداند"""
    t = (text or '').strip().lower()
    if not t:
        return 'empty'

    # کلمات علامتی که هرگز نباید edit در نظر گرفته شوند
    _NON_EDIT_MARKERS = ('کمک', 'راهنما', 'چیکار', 'به من بگو', 'توضیح بده', 'یاد بده')

    # ۱) نیت‌های وزن‌دار - اول همه non-edit نیت‌های قوی را پیدا کن
    matches = []
    for intent, pat, weight in _PATTERNS_WEIGHTED:
        if re.search(pat, t):
            matches.append((intent, weight))

    help_hit = any(i == 'help' for i, _ in matches)
    if help_hit:
        return 'help'

    # ۲) بررسی درخواست ادیت (فقط اگر nیت قوی‌تر دیگری نباشد)
    has_edit_hint = bool(re.search(_EDIT_HINT, t))
    has_area_kw = any(re.search(pat, t) for pat in _AREA_KEYWORDS.values())
    has_marker = any(m in t for m in _NON_EDIT_MARKERS)

    if has_edit_hint and has_area_kw and not has_marker:
        return 'edit'
    if (has_edit_hint and not has_area_kw and not has_marker
            and any(w in t for w in ['میخوام', 'دوست دارم', 'کنم', 'بکن', 'کم کن', 'بده'])):
        return 'edit'

    # ۳) از بین نیت‌های وزن‌دار، بالاترین وزن را بردار
    best_intent = 'chat'
    if matches:
        matches.sort(key=lambda x: -x[1])
        best_intent = matches[0][0]

    # ۴) معرفی اسم
    if _NAME_PAT.search(text):
        return 'name_intro'

    return best_intent


def detect_area(text: str) -> Optional[str]:
    """تشخیص ناحیه مورد نظر کاربر"""
    t = (text or '').strip().lower()
    for area, pat in _AREA_KEYWORDS.items():
        if re.search(pat, t):
            return area
    return None


def extract_name(text: str) -> Optional[str]:
    m = _NAME_PAT.search(text or '')
    return m.group(1).strip() if m else None


def extract_age(text: str) -> Optional[int]:
    m = _AGE_PAT.search(text or '')
    if m:
        try:
            age = int(m.group(1))
            if 10 <= age <= 90:
                return age
        except ValueError:
            pass
    return None


